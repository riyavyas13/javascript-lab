// Task 0.1 - Ternary vs If-Else

// Using ternary operator
let marks = 68;

let result = marks >= 40 ? "Pass" : "Fail";

console.log("Using Ternary Operator:");
console.log(result);


// Using if-else
let marks2 = 68;

console.log("Using If-Else:");

if (marks2 >= 40) {
    console.log("Pass");
} else {
    console.log("Fail");
}