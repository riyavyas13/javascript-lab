// Task 4.2 - Mood Emoji Switch

let mood = "happy";

switch (mood) {
    case "happy":
        console.log(" You are happy! Keep smiling.");
        break;

    case "sad":
        console.log(" It's okay to feel sad. Things will get better.");
        break;

    case "angry":
        console.log(" Take a deep breath and stay calm.");
        break;

    case "tired":
        console.log(" You should take some rest.");
        break;

    default:
        console.log(" Mood not recognized.");
}